//! Native CUDA lowering of matmul-shaped tiles: tensor cores via `wmma`.
//!
//! The same bilinear tile the Metal lowering recognizes
//! (`bilinear_tile`) emitted as CUDA C++: a 64×64 block per 128-thread
//! block, four warps of 32×32, operands staged through shared memory
//! from any affine layout, `wmma` 16×16×8 TF32 fragments with fp32
//! accumulation, and the comp's epilogue run on the stored block.
//!
//! tang-gpu runs on wgpu, which cannot dispatch CUDA; this emitter
//! produces source for an external harness (`scripts/cuda_bench.cu`,
//! compiled with nvcc) that times the kernel against cuBLAS on the same
//! device. The kernel takes the read buffers in `reads` order, then
//! `out`; `TANG_TILES` blocks of `TANG_THREADS` threads.
use std::fmt::Write;

use super::msl::Bilinear;
use super::tile::emit_scalar;
use super::{TensorGraph, TensorId};

const BLOCK: usize = 64;
const CHUNK: usize = 32;
const THREADS: usize = 128;
/// Padded row strides: past the bank period, and keeping every fragment
/// pointer 32-byte aligned as `wmma::load_matrix_sync` requires.
const LDA: usize = CHUNK + 8;
const LDB: usize = BLOCK + 8;
const LDC: usize = BLOCK + 8;

impl TensorGraph {
    /// CUDA source for `root` as a tensor-core tile, or `None` when it is
    /// not matmul-shaped.
    pub fn cuda_mma_kernel(&self, root: usize, reads: &[usize]) -> Option<String> {
        let c = self.comp_at(root)?;
        let Bilinear {
            red_node,
            epilogue,
            buf_a,
            buf_b,
            addr_a,
            addr_b,
            pts,
            dx,
            dy,
            others,
            m,
            n,
            k_total,
            kdim,
        } = self.bilinear_tile(root, reads)?;
        let storage = |j: usize| self.storage(TensorId(j as u32)).n();
        let tiles_x = n.div_ceil(BLOCK);
        let tiles_y = m.div_ceil(BLOCK);
        let n_tiles = tiles_x * tiles_y * others.iter().map(|&d| pts[d]).product::<usize>();
        let w_out = c.width();
        let arena = (BLOCK * LDA + CHUNK * LDB).max(BLOCK * LDC);

        let mut s = String::new();
        writeln!(s, "// Auto-generated by tang-compile: wmma (TF32) tile").unwrap();
        writeln!(s, "#include <mma.h>").unwrap();
        writeln!(s, "using namespace nvcuda;").unwrap();
        writeln!(s, "#define TANG_TILES {n_tiles}").unwrap();
        writeln!(s, "#define TANG_THREADS {THREADS}").unwrap();
        writeln!(s, "#define TANG_OUT_LEN {}", numel_pts(&pts) * w_out).unwrap();
        writeln!(s, "#define select(f, t, c) ((c) ? (t) : (f))").unwrap();
        let mut params: Vec<String> = reads
            .iter()
            .map(|&j| format!("const float* __restrict__ b{j}"))
            .collect();
        params.push("float* __restrict__ out".into());
        writeln!(
            s,
            "extern \"C\" __global__ void __launch_bounds__({THREADS}) tang_kernel({}) {{",
            params.join(", ")
        )
        .unwrap();
        writeln!(s, "    __shared__ __align__(32) float smem[{arena}];").unwrap();
        writeln!(s, "    float* As = smem;").unwrap();
        writeln!(s, "    float* Bs = smem + {}u;", BLOCK * LDA).unwrap();
        writeln!(s, "    float* Cs = smem;").unwrap();
        writeln!(s, "    unsigned tile = blockIdx.x;").unwrap();
        writeln!(s, "    if (tile >= {n_tiles}u) return;").unwrap();
        writeln!(s, "    unsigned tile_x = tile % {tiles_x}u;").unwrap();
        writeln!(s, "    unsigned tile_y = (tile / {tiles_x}u) % {tiles_y}u;").unwrap();
        writeln!(s, "    unsigned lead = tile / {}u;", tiles_x * tiles_y).unwrap();
        for &d in others.iter().rev() {
            writeln!(s, "    unsigned p{d} = lead % {}u;", pts[d]).unwrap();
            writeln!(s, "    lead = lead / {}u;", pts[d]).unwrap();
        }
        writeln!(s, "    unsigned row0 = tile_y * {BLOCK}u;").unwrap();
        writeln!(s, "    unsigned col0 = tile_x * {BLOCK}u;").unwrap();
        let lead_term = |addr: &super::msl::Addr| -> String {
            let mut t = format!("{}", addr.offset);
            for &d in &others {
                if addr.coefs[d] != 0 {
                    t.push_str(&format!(" + {} * (int)p{d}", addr.coefs[d]));
                }
            }
            t
        };
        writeln!(s, "    int base_a = {};", lead_term(&addr_a)).unwrap();
        writeln!(s, "    int base_b = {};", lead_term(&addr_b)).unwrap();
        writeln!(s, "    unsigned tid = threadIdx.x;").unwrap();
        writeln!(s, "    unsigned warp = tid / 32u;").unwrap();
        writeln!(s, "    unsigned wr = (warp / 2u) * 32u;").unwrap();
        writeln!(s, "    unsigned wc = (warp % 2u) * 32u;").unwrap();
        writeln!(
            s,
            "    wmma::fragment<wmma::accumulator, 16, 16, 8, float> acc[2][2];"
        )
        .unwrap();
        writeln!(s, "    for (int i = 0; i < 2; i++) for (int j = 0; j < 2; j++) wmma::fill_fragment(acc[i][j], 0.0f);").unwrap();
        writeln!(
            s,
            "    for (unsigned k0 = 0u; k0 < {k_total}u; k0 += {CHUNK}u) {{"
        )
        .unwrap();
        // staging, walking the buffer in address order
        let stage = |s: &mut String,
                     name: &str,
                     addr: &super::msl::Addr,
                     pdim: usize,
                     base: &str,
                     extent: usize,
                     buf: usize,
                     row_major: bool| {
            let (cp, ck) = (addr.coefs[pdim], addr.coefs[kdim]);
            let k_inner = ck.unsigned_abs() <= cp.unsigned_abs();
            writeln!(
                s,
                "        for (unsigned idx = tid; idx < {}u; idx += {THREADS}u) {{",
                BLOCK * CHUNK
            )
            .unwrap();
            if k_inner {
                writeln!(
                    s,
                    "            unsigned kk = idx % {CHUNK}u; unsigned pt = idx / {CHUNK}u;"
                )
                .unwrap();
            } else {
                writeln!(
                    s,
                    "            unsigned pt = idx % {BLOCK}u; unsigned kk = idx / {BLOCK}u;"
                )
                .unwrap();
            }
            writeln!(
                s,
                "            unsigned gp = {base} + pt; unsigned gk = k0 + kk;"
            )
            .unwrap();
            let slot = if row_major {
                format!("pt * {LDA}u + kk")
            } else {
                format!("kk * {LDB}u + pt")
            };
            writeln!(
                s,
                "            {name}[{slot}] = (gp < {extent}u && gk < {k_total}u) ? b{buf}[(unsigned)(base_{} + {cp} * (int)gp + {ck} * (int)gk)] : 0.0f;",
                if row_major { "a" } else { "b" }
            )
            .unwrap();
            writeln!(s, "        }}").unwrap();
        };
        stage(&mut s, "As", &addr_a, dy, "row0", m, buf_a, true);
        stage(&mut s, "Bs", &addr_b, dx, "col0", n, buf_b, false);
        writeln!(s, "        __syncthreads();").unwrap();
        writeln!(
            s,
            "        for (unsigned kk = 0u; kk < {CHUNK}u; kk += 8u) {{"
        )
        .unwrap();
        writeln!(s, "            wmma::fragment<wmma::matrix_a, 16, 16, 8, wmma::precision::tf32, wmma::row_major> a[2];").unwrap();
        writeln!(s, "            wmma::fragment<wmma::matrix_b, 16, 16, 8, wmma::precision::tf32, wmma::row_major> b[2];").unwrap();
        writeln!(s, "            for (int i = 0; i < 2; i++) {{").unwrap();
        writeln!(s, "                wmma::load_matrix_sync(a[i], As + (wr + 16u * i) * {LDA}u + kk, {LDA}u);").unwrap();
        writeln!(s, "                for (int t = 0; t < a[i].num_elements; t++) a[i].x[t] = wmma::__float_to_tf32(a[i].x[t]);").unwrap();
        writeln!(s, "            }}").unwrap();
        writeln!(s, "            for (int j = 0; j < 2; j++) {{").unwrap();
        writeln!(s, "                wmma::load_matrix_sync(b[j], Bs + kk * {LDB}u + wc + 16u * j, {LDB}u);").unwrap();
        writeln!(s, "                for (int t = 0; t < b[j].num_elements; t++) b[j].x[t] = wmma::__float_to_tf32(b[j].x[t]);").unwrap();
        writeln!(s, "            }}").unwrap();
        writeln!(s, "            for (int i = 0; i < 2; i++) for (int j = 0; j < 2; j++) wmma::mma_sync(acc[i][j], a[i], b[j], acc[i][j]);").unwrap();
        writeln!(s, "        }}").unwrap();
        writeln!(s, "        __syncthreads();").unwrap();
        writeln!(s, "    }}").unwrap();
        writeln!(s, "    for (int i = 0; i < 2; i++) for (int j = 0; j < 2; j++) wmma::store_matrix_sync(Cs + (wr + 16u * i) * {LDC}u + wc + 16u * j, acc[i][j], {LDC}u, wmma::mem_row_major);").unwrap();
        writeln!(s, "    __syncthreads();").unwrap();
        writeln!(
            s,
            "    for (unsigned idx = tid; idx < {}u; idx += {THREADS}u) {{",
            BLOCK * BLOCK
        )
        .unwrap();
        writeln!(s, "        unsigned p{dy} = row0 + idx / {BLOCK}u;").unwrap();
        writeln!(s, "        unsigned p{dx} = col0 + idx % {BLOCK}u;").unwrap();
        writeln!(s, "        if (p{dy} < {m}u && p{dx} < {n}u) {{").unwrap();
        writeln!(
            s,
            "            float red = Cs[(idx / {BLOCK}u) * {LDC}u + idx % {BLOCK}u];"
        )
        .unwrap();
        let vals: Vec<String> = if epilogue {
            let prank = c.points().len();
            let mut arg_vals = Vec::new();
            for a in &c.args {
                if a.src.n() == red_node {
                    arg_vals.push("red".to_string());
                    continue;
                }
                let addr = self.flat_addr(a, prank);
                let mut e = format!("{}", addr.offset);
                for (d, &coef) in addr.coefs.iter().enumerate() {
                    if coef != 0 {
                        e.push_str(&format!(" + {coef} * (int)p{d}"));
                    }
                }
                arg_vals.push(format!("b{}[(unsigned)({e})]", storage(a.src.n())));
            }
            let mut body = String::new();
            let outs = emit_scalar(&mut body, &c.body, &c.body_outs, "e0_", &|v| {
                arg_vals[v as usize].clone()
            });
            for line in body.lines() {
                writeln!(s, "            {}", line.replacen("let ", "float ", 1)).unwrap();
            }
            outs
        } else {
            vec!["red".to_string()]
        };
        let mut flat = String::from("0u");
        for (d, &np) in pts.iter().enumerate() {
            flat = format!("({flat}) * {np}u + p{d}");
        }
        writeln!(s, "            unsigned g = {flat};").unwrap();
        for (slot, v) in vals.iter().enumerate() {
            writeln!(s, "            out[g * {w_out}u + {slot}u] = {v};").unwrap();
        }
        writeln!(s, "        }}").unwrap();
        writeln!(s, "    }}").unwrap();
        writeln!(s, "}}").unwrap();
        Some(s)
    }

    /// The CUDA tensor-core kernel for the one tiled matmul in `outputs`'
    /// program, with its read buffers in binding order. For the harness.
    pub fn cuda_mma_program(&self, outputs: &[TensorId]) -> Option<(String, Vec<TensorId>)> {
        let live = self.live(outputs);
        for root in (0..self.nodes.len()).filter(|&i| live[i] && !self.nodes[i].inline) {
            if self.nodes[root].tile.0 == 0 {
                continue;
            }
            let order = self.inline_closure(root);
            let reads: Vec<usize> = order
                .iter()
                .copied()
                .filter(|&j| {
                    j != root
                        && !self.nodes[j].inline
                        && !matches!(self.nodes[j].op, super::Op::Iota(_) | super::Op::Reshape(_))
                })
                .collect();
            if let Some(src) = self.cuda_mma_kernel(root, &reads) {
                return Some((src, reads.iter().map(|&j| TensorId(j as u32)).collect()));
            }
        }
        None
    }
}

fn numel_pts(pts: &[usize]) -> usize {
    pts.iter().product()
}
